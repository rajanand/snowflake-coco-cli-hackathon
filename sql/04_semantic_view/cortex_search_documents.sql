ALTER STAGE SUPPLY_CHAIN.SEMANTIC_MODELS.SUPPLIER_CONTRACTS_STAGE REFRESH;

CREATE OR REPLACE TABLE SUPPLY_CHAIN.SEMANTIC_MODELS.supplier_contract_documents (
    supplier_id VARCHAR COMMENT 'Extracted from filename, e.g. SUP-0002_contract.pdf -> SUP-0002.',
    file_name VARCHAR,
    parsed_content VARCHAR COMMENT 'Full contract text extracted via AI_PARSE_DOCUMENT (LAYOUT mode) -- unstructured source, no structured payment_terms/penalty columns exist upstream; Cortex Search reads this text directly.',
    page_count NUMBER,
    parsed_at TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
) COMMENT = 'Unstructured document intelligence: AI_PARSE_DOCUMENT output over synthetic supplier contract PDFs. Feeds the Cortex Search service used by the DocumentQAAgent (agents/agent_router.py) and the post-query enrichment hook.';

INSERT INTO SUPPLY_CHAIN.SEMANTIC_MODELS.supplier_contract_documents (supplier_id, file_name, parsed_content, page_count)
SELECT
    SPLIT_PART(relative_path, '_', 1) AS supplier_id,
    relative_path AS file_name,
    parsed:content::STRING AS parsed_content,
    parsed:metadata:pageCount::NUMBER AS page_count
FROM (
    SELECT
        relative_path,
        AI_PARSE_DOCUMENT(
            TO_FILE('@SUPPLY_CHAIN.SEMANTIC_MODELS.SUPPLIER_CONTRACTS_STAGE', relative_path),
            {'mode': 'LAYOUT'}
        ) AS parsed
    FROM DIRECTORY(@SUPPLY_CHAIN.SEMANTIC_MODELS.SUPPLIER_CONTRACTS_STAGE)
    WHERE relative_path ILIKE '%.pdf'
);

CREATE OR REPLACE CORTEX SEARCH SERVICE SUPPLY_CHAIN.SEMANTIC_MODELS.SUPPLY_CHAIN_DOCUMENTS
    ON parsed_content
    ATTRIBUTES supplier_id, file_name
    WAREHOUSE = COMPUTE_WH
    TARGET_LAG = '1 HOUR'
    COMMENT = 'Cortex Search over AI_PARSE_DOCUMENT-parsed supplier contract PDFs (payment terms, SLA penalty clauses). Feeds the DocumentQAAgent and the agent router''s post-query enrichment hook -- the document-intelligence demo moment: "Does our contract with Supplier X have an SLA penalty for late delivery?"'
    AS (
        SELECT supplier_id, file_name, parsed_content
        FROM SUPPLY_CHAIN.SEMANTIC_MODELS.supplier_contract_documents
    );

-- -----------------------------------------------------------------------------
