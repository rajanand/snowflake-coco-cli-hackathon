-- =============================================================================
-- Phase 4/8: Document Intelligence -- Cortex Search over supplier contracts
-- =============================================================================
-- This is the ONE genuinely unstructured data source in the project. Every
-- other Bronze/Silver/Gold table is structured (typed columns) or, at most,
-- semi-structured (SOURCE_IOT_SENSOR's nested sensor JSON). Supplier
-- contracts are free-form legal prose -- payment terms and SLA penalty
-- clauses buried in paragraphs, not columns -- which is exactly why they
-- need AI_PARSE_DOCUMENT + Cortex Search rather than a relational table.
--
-- Pipeline: PDF (unstructured) -> stage -> AI_PARSE_DOCUMENT (LAYOUT mode,
-- text extraction) -> supplier_contract_documents (parsed text table) ->
-- Cortex Search service -> DocumentQAAgent (agents/agent_router.py) and the
-- post-query enrichment hook.
--
-- Source PDFs are generated by data_generation/generate_supplier_contracts.py
-- (11 synthetic supplier contracts, deterministic per supplier, varying
-- payment terms and late-delivery penalty clauses -- one supplier
-- deliberately has NO penalty clause as a negative-case test).
--
-- IMPORTANT: AI_PARSE_DOCUMENT incurs Cortex AI function usage cost. Check
-- current rates before running: https://docs.snowflake.com/en/user-guide/cost-understanding-overall#service-type
-- =============================================================================

